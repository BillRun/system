/**
 * Billing Job Manager
 *
 * @package  Job Manager
 * @since    5.16
 */
class Billrun_Jobsmanager {

	protected $method = 'jobmanager';
	
	/**
	 * array container of singleton
	 * @var array
	 */
	static protected $instances = [];
	
	/**
	 * the queue that job is managed in
	 * 
	 * @var Zend_Queue
	 */
	protected $queue;
	
	/**
	 * the timeout of the job to be pulled before the same job will be pulled again if not done
	 * 
	 * @var type int
	 */
	protected $timeout = 3600;
	
	/**
	 * the timeout of the job to be pulled before the same job will be pulled again if not done
	 * 
	 * @var type int
	 */
	protected $lastError = '';

	protected function __construct($params = []) {
		foreach ($params as $k => $v) {
			if (property_exists($this, $k)) {
				$this->$k = $v;
			}
		}
	}

	/**
	 * push job into queue 
	 * @param string $type the type of the job
	 * @param array $config the configuration of the job
	 * @param string $parent the parent task if available
	 * @param int $schedule schedule the job for future; unix timestamp
	 * @return type
	 */
	public function push($type, $config, $parent = null, $schedule = null) {
		$this->lastError = '';
		if (!$this->validateInput($type, $config)) {
			return false;
		}
		$jobSettings = ['type' => $type, 'config' => $config];
		if (!empty($parent)) {
			$jobSettings['parent'] = $parent;
		}
		
		if (!empty($schedule)) {
			if (!is_numeric($schedule)) { // let's convert it to unix timestamp
				$jobSettings['schedule'] = strtotime($schedule);
			} else {
				$jobSettings['schedule'] = (int) $schedule;
			}
		}

		$msg = $this->queue->send($jobSettings);
		$ret = Mongodloid_Result::getResult($msg->toArray());
		$this->audit($type, $ret);
		return $ret;
	}
	
	/**
	 * log parent jobs to audit
	 */
	protected function audit($type, $msg) {
		if (strpos($type, '_') === false) { // if this is not child job that is generated by the system
			Billrun_AuditTrail_Util::trackChanges('create', $msg['md5'], 'jobs_messages', null, $msg);
		}
	}

	protected function validateInput($job_type, $config) {
		if (!class_exists('Billrun_Job_' . $job_type) && !class_exists('Customjob_' . $job_type)) {
			$this->lastError = "job type " . $job_type . " is not exists";
			Billrun_Factory::log($this->lastError, Zend_Log::WARN);
			return false;
		}
		return true;
	}
	
	public function getLastError() {
		$ret = $this->lastError;
		$this->lastError = '';
		return $ret;
	}

	public function pull() {
		$jobsQueue = $this->queue->receive(1, $this->timeout);
		foreach ($jobsQueue as $k => $entry) {
			if (empty($entry->body['type'])) {
				return false;
			}
			$class = 'Billrun_Job_' . (string) $entry->body['type'];
			if (!class_exists($class)) {
				$class = 'Customjob_' . (string) $entry->body['type'];
			}
			$job = new $class($entry);
		}
		return $job ?? false;
	}

	/**
	 * query the messages of a queue (the jobs pushed to it - pending or done)
	 * 
	 * @param array $query mongo query on the message fields, e.g. body.type, body.config.<field>, done
	 * @param array $sort sort of the result, e.g. ['created' => -1] for the latest message first
	 * @param int $limit max number of messages to return; 0 for all
	 * @param string $queueName the queue whose messages to query; the jobs queue by default
	 * 
	 * @return Mongodloid_Cursor the matching messages
	 */
	public static function getMessages($query, $sort = [], $limit = 0, $queueName = 'jobs') {
		$cursor = Billrun_Factory::db()->getCollection($queueName . '_messages')->query($query)->cursor();
		if (!empty($sort)) {
			$cursor->sort($sort);
		}
		if (!empty($limit)) {
			$cursor->limit($limit);
		}
		return $cursor;
	}

	/**
	 * check if a job message is done: the job ran to its end (deleteMessage), gave up (its run limit
	 * exceeded) or was cancelled; until then the message is pending - waiting to be pulled (again)
	 * 
	 * @param Mongodloid_Entity|array $message a message of the queue (see getMessages)
	 * 
	 * @return bool true if done, false if still pending
	 */
	public static function isDone($message) {
		return !empty($message['done']);
	}

	/**
	 * set fields on a message of a queue - a job's own data on its message, e.g. a stamp it leaves for
	 * whoever reads the message later; the queue's own fields (done, try, timeout...) are not meant to be set here
	 * 
	 * @param string $md5 the message id
	 * @param array $fields the fields to set, e.g. ['notified_at' => new Mongodloid_Date()]
	 * @param string $queueName the queue of the message; the jobs queue by default
	 * 
	 * @return bool true if the update succeeded, else false
	 */
	public static function updateMessage($md5, $fields, $queueName = 'jobs') {
		Billrun_Factory::log("Update " . $queueName . " message " . $md5 . " fields " . implode(', ', array_keys($fields)), Zend_Log::DEBUG);
		$result = Billrun_Factory::db()->getCollection($queueName . '_messages')->update(['md5' => $md5], ['$set' => $fields]);
		if (empty($result['n'])) {
			Billrun_Factory::log("Update " . $queueName . " message " . $md5 . " failed. Result: " . print_r($result, 1), Zend_Log::DEBUG);
			return false;
		}
		return true;
	}

	/**
	 * singletone of queue instance
	 * 
	 * @param Zend_Queue $queue the queue that the job manager is running on
	 * 
	 * @return Billrun_Jobsmanager
	 */
	public static function getInstance($queue = null) {
		if (empty($queue)) {
			$queue = Billrun_Factory::queue('jobs');
		}
		$queueName = $queue->getName();
		if (empty(self::$instances[$queueName])) {
			self::$instances[$queueName] = new self(['queue' => $queue, 'timeout' => $queue->getOption('timeout')]);
		}
		return self::$instances[$queueName];
	}
	
	public static function cleanInstance($queue = null) {
		if (is_null($queue)) {
			$queueName = 'jobs';
		} else {
			$queueName = $queue->getName();
		}
		Billrun_Factory::cleanQueue($queueName);
		self::$instances[$queueName] = null;
	}
	
	/**
	 * check if the worker is enabled
	 * 
	 * @return boolean true if enabled else false
	 */
	public function isWorkerEnabled() {
		return Billrun_Factory::config()->getConfigValue('worker.enabled', false);
	}

}
